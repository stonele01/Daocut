import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdir, mkdtemp, readFile, rm } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { chromium } from 'playwright-core';
import { startStudio } from './server.mjs';

test('candidate preview plays synthetic audio without changing film', { timeout: 90000 }, async () => {
  const base = resolve('.test-temp'); await mkdir(base, { recursive: true });
  const scratch = await mkdtemp(join(base, 'product-browser-'));
  process.env.DAOCUT_STUDIO_HOME = join(scratch, 'home'); process.env.DAOCUT_LIBRARY = join(scratch, 'library'); process.env.DAOCUT_TRASH_DIR = join(scratch, 'trash');
  await mkdir(process.env.DAOCUT_TRASH_DIR);
  let studio, browser;
  try {
    studio = await startStudio({ port: 0, openBrowser: () => {} });
    const api = async (path, method = 'GET', body) => { const res = await fetch(`${studio.origin}${path}`, { method, headers: { 'x-studio-key': studio.key, ...(body ? { 'content-type': 'application/json' } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) }); const value = await res.json(); assert.equal(res.status, 200, JSON.stringify(value)); return value; };
    const { project } = await api('/api/projects', 'POST', { path: join(scratch, 'synthetic-project') });
    await mkdir(join(project.path, 'assets'), { recursive: true });
    for (const name of ['synthetic-a.mp4', 'synthetic-b.mp4']) execFileSync('ffmpeg', ['-v', 'error', '-f', 'lavfi', '-i', 'color=c=blue:s=64x64:r=10:d=12', '-f', 'lavfi', '-i', 'sine=frequency=440:duration=12', '-c:a', 'aac', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-y', join(project.path, 'assets', name)], { windowsHide: true });
    const tags = ['钩子', '痛点', '卖点', '产品演示', '价格锚点', '行动指令'];
    const analysis = { version: 1, sources: [{ id: 'a', assetPath: 'assets/synthetic-a.mp4', durationMs: null }, { id: 'b', assetPath: 'assets/synthetic-b.mp4', durationMs: null }], products: [{ id: 'p1', name: '虚构示例甲', sourceIds: ['a', 'b'] }, { id: 'p2', name: '虚构示例乙', sourceIds: ['a', 'b'] }], intervals: [{ id: 'i1', productId: 'p1', sourceId: 'a', startMs: 0, endMs: 5000 }, { id: 'i2', productId: 'p1', sourceId: 'b', startMs: 4000, endMs: 9000 }, { id: 'i3', productId: 'p1', sourceId: 'a', startMs: 7000, endMs: 9000 }, { id: 'i4', productId: 'p2', sourceId: 'a', startMs: 9500, endMs: 11000 }], candidates: tags.map((tag, n) => ({ id: `c${n}`, productId: 'p1', intervalId: n === 5 ? 'i2' : 'i1', sourceId: n === 5 ? 'b' : 'a', startMs: n === 5 ? 6000 : 1000 + n * 100, endMs: n === 5 ? 8000 : 3000 + n * 100, text: `虚构样例${tag}`, tags: [tag], origin: 'synthetic-test', version: 1 })) };
    analysis.products.push({ id: 'p3', name: '虚构示例丙（未分析）', sourceIds: ['b'] });
    analysis.candidates[0].origin = 'ai-text';
    analysis.candidates[0].review = 'visual-unverified';
    analysis.candidates[0].runId = 'mock-run';
    analysis.scopes = [{ id: 'scope', kind: 'confirmed-inspection', confirmed: true, sourceId: 'a', productId: 'p1', startMs: 0, endMs: 12000 }];
    analysis.candidates[0].intervalId = 'scope';
    analysis.candidates[0].details = { subtypes: ['模拟类型'], reason: '模拟依据', evidence: ['ASR'], context: '模拟上下文', repetition: '模拟重复', review: ['画面待核实'] };
    analysis.intervals.push({ id: 'i5', productId: 'p3', sourceId: 'b', startMs: 9000, endMs: 11000 });
    await api(`/api/projects/${project.id}/product-analysis`, 'PUT', { analysis });
    browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
    const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
    let live = { transcription: { status: 'failed', retryBlocked: true, model: '模拟转写模型', segments: [] }, analysis: { status: 'idle', model: '模拟文字模型' } };
    const liveRequests = [];
    await page.route('**/live-analysis**', async route => {
      const request = route.request(); liveRequests.push({ url: request.url(), method: request.method(), body: request.method() === 'POST' ? request.postDataJSON() : null });
      if (request.method() === 'POST' && request.url().endsWith('/transcribe')) live = { ...live, transcription: { status: 'complete', model: '模拟转写模型', segments: [{ startMs: 1000, endMs: 2000, text: '合成转写文字' }] } };
      if (request.method() === 'POST' && request.url().endsWith('/analyze')) live = { ...live, analysis: { status: 'complete', model: '模拟文字模型', stale: false, currentRunId: 'mock-run', coverage: [{ sourceId: 'a', intervalId: 'scope', asrRanges: [[1000, 2000]], audioRanges: [], videoRanges: [] }], issues: ['模拟待核实事项'] } };
      await route.fulfill({ json: live });
    });
    await page.goto(`${studio.origin}/projects/${project.id}?key=${studio.key}`);
    await page.getByRole('button', { name: '商品与结构' }).click();
    await page.getByRole('button', { name: '虚构示例甲' }).first().waitFor();
    await page.getByText('上次提交状态不确定，请先核查服务状态。').waitFor();
    assert.equal(await page.getByRole('button', { name: '重试转写' }).count(), 0);
    live = { ...live, transcription: { status: 'idle', model: '模拟转写模型', segments: [] } };
    await page.reload();
    await page.getByRole('button', { name: '商品与结构' }).click();
    await page.getByRole('button', { name: '虚构示例甲' }).first().waitFor();
    const filmPath = join(project.path, 'film.html');
    const analysisPath = join(project.path, '.film', 'product-analysis.json');
    const beforeFilm = await readFile(filmPath, 'utf8');
    const beforeAnalysis = await readFile(analysisPath, 'utf8');
    const candidatePanel = page.getByLabel('候选片段');
    const firstCandidate = candidatePanel.locator('article').filter({ hasText: '虚构样例钩子' });
    await firstCandidate.getByText('虚构样例钩子').click();
    await page.waitForFunction(() => [...document.querySelectorAll('video')].some(v => v.currentSrc.includes('synthetic-a.mp4') && v.readyState >= 1 && v.currentTime >= 1 && v.paused));
    const video = page.locator('video').first();
    assert.equal(await video.evaluate(v => v.paused), true, 'card click only locates');
    await firstCandidate.getByRole('button', { name: '预览' }).click();
    await page.waitForFunction(() => [...document.querySelectorAll('video')].some(v => v.currentSrc.includes('synthetic-a.mp4') && !v.paused && v.currentTime > 1.3));
    const playback = await video.evaluate(v => ({ muted: v.muted, volume: v.volume, audioBytes: v.webkitAudioDecodedByteCount }));
    assert.equal(playback.muted, false); assert.ok(playback.volume > 0);
    assert.ok(playback.audioBytes > 0, 'browser decoded the synthetic audio track');
    await page.getByRole('button', { name: /^行动指令\s+\d+$/ }).click();
    await candidatePanel.getByText('虚构样例行动指令').click();
    await page.waitForFunction(() => [...document.querySelectorAll('video')].some(v => v.currentSrc.includes('synthetic-b.mp4') && v.currentTime >= 6 && v.paused));
    assert.equal(await readFile(filmPath, 'utf8'), beforeFilm, 'source preview must not edit film');
  } finally { await browser?.close(); await studio?.close(); await rm(scratch, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 }); }
});
