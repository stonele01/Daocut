import { test } from 'node:test';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { chromium } from 'playwright-core';
import { startStudio } from './server.mjs';
import { filmHtml } from '../../src/film-doc.mjs';

test('source axis with isolated synthetic media', { timeout: 120000 }, async () => {
  const base = resolve('../../.tmp'); await mkdir(base, { recursive: true });
  const scratch = await mkdtemp(join(base, 'source-axis-verified-'));
  const oldEnv = Object.fromEntries(['DAOCUT_STUDIO_HOME', 'DAOCUT_LIBRARY', 'DAOCUT_TRASH_DIR'].map(k => [k, process.env[k]]));
  process.env.DAOCUT_STUDIO_HOME = join(scratch, 'home'); process.env.DAOCUT_LIBRARY = join(scratch, 'library'); process.env.DAOCUT_TRASH_DIR = join(scratch, 'trash');
  await mkdir(process.env.DAOCUT_TRASH_DIR);
  let studio, browser, step = 'setup';
  try {
    studio = await startStudio({ port: 0, openBrowser: () => {} });
    const api = async (path, method = 'GET', body) => {
      const r = await fetch(`${studio.origin}${path}`, { method, headers: { 'x-studio-key': studio.key, ...(body ? { 'content-type': 'application/json' } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
      assert.equal(r.status, 200, 'fixture API failed'); return r.json();
    };
    const { project } = await api('/api/projects', 'POST', { path: join(scratch, 'synthetic-project') });
    await mkdir(join(project.path, 'assets'), { recursive: true });
    for (const name of ['a', 'b']) execFileSync('ffmpeg', ['-v', 'error', '-f', 'lavfi', '-i', 'testsrc2=s=320x180:r=10:d=30', '-f', 'lavfi', '-i', 'sine=frequency=440:duration=30', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-c:a', 'aac', '-shortest', '-y', join(project.path, 'assets', `synthetic-${name}.mp4`)], { windowsHide: true });
    const tags = ['钩子', '痛点', '卖点', '产品演示', '价格锚点', '行动指令'];
    const starts = [1000, 4000, 7000, 10000, 17000, 22000];
    const analysis = { version: 1, sources: ['a', 'b'].map(id => ({ id, assetPath: `assets/synthetic-${id}.mp4`, durationMs: null })), products: [{ id: 'p', name: '合成测试商品', sourceIds: ['a', 'b'] }], intervals: [{ id: 'i', productId: 'p', sourceId: 'a', startMs: 0, endMs: 29000 }, { id: 'j', productId: 'p', sourceId: 'b', startMs: 15000, endMs: 29000 }], candidates: [...tags.map((tag, n) => ({ id: `c${n}`, productId: 'p', intervalId: 'i', sourceId: 'a', startMs: starts[n], endMs: starts[n] + 2500, text: `合成${tag}`, tags: [tag], origin: 'synthetic-test', version: 1 })), { id: 'tiny', productId: 'p', intervalId: 'i', sourceId: 'a', startMs: 3950, endMs: 3999, text: '合成短候选', tags: ['钩子'], origin: 'synthetic-test', version: 1 }, { id: 'multi', productId: 'p', intervalId: 'i', sourceId: 'a', startMs: 12000, endMs: 16000, text: '合成多标签', tags: ['钩子', '痛点'], origin: 'synthetic-test', version: 1 }, { id: 'other', productId: 'p', intervalId: 'j', sourceId: 'b', startMs: 20000, endMs: 23000, text: '合成切换来源', tags: ['行动指令'], origin: 'synthetic-test', version: 1 }] };
    await api(`/api/projects/${project.id}/product-analysis`, 'PUT', { analysis });
    const filmPath = join(project.path, 'film.html');
    await writeFile(filmPath, filmHtml({ stage: { w: 320, h: 180 }, tracks: [{ clips: [{ id: 'synthetic-clip', src: 'assets/synthetic-a.mp4', at: 0, time: [0, 2] }] }] }));
    const before = await readFile(filmPath, 'utf8');
    const analysisPath = join(project.path, '.film', 'product-analysis.json');
    const beforeAnalysis = await readFile(analysisPath, 'utf8');
    const mediaPath = join(project.path, 'assets', 'synthetic-b.mp4');
    const hash = async () => createHash('sha256').update(await readFile(mediaPath)).digest('hex');
    const beforeHash = await hash();
    const hashA = async () => createHash('sha256').update(await readFile(join(project.path, 'assets', 'synthetic-a.mp4'))).digest('hex');
    const beforeHashA = await hashA();
    browser = await chromium.launch({ executablePath: process.env.DAOCUT_TEST_BROWSER || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
    const page = await browser.newPage({ viewport: { width: 1600, height: 1050 } });
    await page.route('**/live-analysis**', route => route.fulfill({ json: { transcription: { status: 'idle', segments: [] }, analysis: { status: 'idle' } } }));
    step = 'open synthetic project';
    await page.goto(`${studio.origin}/projects/${project.id}?key=${studio.key}`);
    await page.getByRole('button', { name: '商品与结构' }).click();
    await page.getByRole('button', { name: '合成测试商品' }).first().waitFor();
    const axis = page.locator('[data-source-axis]'); await axis.waitFor();
    step = 'tiny gap keeps identity across zoom';
    const tinyGap = axis.locator('[data-source-context="3999:4000"]');
    await tinyGap.waitFor();
    const tinyBefore = await tinyGap.getAttribute('data-source-context');
    const rowBefore = await axis.locator('[data-source-candidate="c1"]').evaluate(el => el.style.top);
    step = 'candidate source range';
    const candidate = axis.locator('[data-source-candidate="c4"]');
    await candidate.waitFor();
    for (let i = 0; i < 3; i++) await axis.getByRole('button', { name: '放大时间轴' }).click();
    assert.equal(await tinyGap.getAttribute('data-source-context'), tinyBefore);
    const rowAfter = await axis.locator('[data-source-candidate="c1"]').evaluate(el => el.style.top);
    assert.notEqual(rowAfter, rowBefore, 'short candidate shifts visual row with zoom while gap identity stays');
    await candidate.scrollIntoViewIfNeeded();
    const initial = async () => ({ start: Number(await candidate.getAttribute('data-start-ms')), end: Number(await candidate.getAttribute('data-end-ms')) });
    assert.deepEqual(await initial(), {start:17000,end:19500});
    const edge = async (which, dx, block = candidate) => {
      const handle = block.locator(`[data-source-trim="${which}"]`);
      await handle.scrollIntoViewIfNeeded();
      const box = await handle.boundingBox(); assert.ok(box);
      await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
      await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + dx, box.y + box.height / 2, {steps: 20}); await page.mouse.up();
      await page.waitForTimeout(400);
    };
    await edge('start', -30);
    const left = await initial(); assert.ok(left.start < 17000 && left.end === 19500, `left trim ${JSON.stringify(left)}`);
    await edge('end', 30);
    const expanded = await initial(); assert.ok(expanded.start < 17000 && expanded.end > 19500, `right trim ${JSON.stringify(expanded)}`);
    assert.equal(await readFile(filmPath, 'utf8'), before, 'source trim alone does not write the film');
    assert.equal(await readFile(analysisPath, 'utf8'), beforeAnalysis, 'source trim does not change analysis');
    step = 'drop adjusted source range';
    const dock = page.locator('[data-timeline-scope="main"]');
    const filmBlock = dock.locator('[data-block-kind="video"]').first();
    const src = await candidate.boundingBox(), dest = await filmBlock.boundingBox(); assert.ok(src && dest);
    await page.mouse.move(src.x + src.width / 2, src.y + src.height / 2); await page.mouse.down();
    await page.mouse.move(dest.x + dest.width / 2, dest.y + dest.height / 2, {steps: 30}); await page.mouse.up();
    await page.waitForTimeout(1800);
    const filmAfterDrop = await readFile(filmPath, 'utf8');
    assert.notEqual(filmAfterDrop, before, 'explicit drop changes the film');
    const sourceStart = String(expanded.start / 1000), sourceEnd = String(expanded.end / 1000);
    assert.ok(filmAfterDrop.includes(`synthetic-a.mp4#t=${sourceStart},${sourceEnd}`), `dropped bounds ${sourceStart},${sourceEnd}`);
    await edge('end', 20);
    assert.equal(await readFile(filmPath, 'utf8'), filmAfterDrop, 'later source trim leaves already inserted film unchanged');
    const latest = await initial();
    assert.equal(await readFile(analysisPath, 'utf8'), beforeAnalysis);
    step = 'reload preserves source range';
    await page.reload(); await page.getByRole('button', { name: '商品与结构' }).click();
    await candidate.waitFor(); assert.deepEqual(await initial(), latest);
    assert.equal(await readFile(filmPath, 'utf8'), filmAfterDrop);
    assert.equal(await readFile(analysisPath, 'utf8'), beforeAnalysis);
    step = 'double click restores candidate and gray range trims';
    await candidate.locator('[data-source-trim="start"]').dblclick();
    assert.deepEqual(await initial(), { start: 17000, end: 19500 });
    for (let i = 0; i < 3; i++) await axis.getByRole('button', { name: '放大时间轴' }).click();
    const gray = axis.locator('[data-source-context="19500:22000"]');
    await gray.waitFor();
    const grayRange = async () => ({ start: Number(await gray.getAttribute('data-start-ms')), end: Number(await gray.getAttribute('data-end-ms')) });
    assert.deepEqual(await grayRange(), { start: 19500, end: 22000 });
    await edge('start', -30, gray);
    const grayLeft = await grayRange(); assert.ok(grayLeft.start < 19500 && grayLeft.end === 22000, `gray left ${JSON.stringify(grayLeft)}`);
    await edge('end', 30, gray);
    const grayExpanded = await grayRange(); assert.ok(grayExpanded.start < 19500 && grayExpanded.end > 22000, `gray right ${JSON.stringify(grayExpanded)}`);
    await page.waitForFunction(ms => [...document.querySelectorAll('video')].some(v => v.currentSrc.includes('synthetic-a.mp4') && !v.seeking && Math.abs(v.currentTime * 1000 - ms) < 200), grayExpanded.end, { timeout: 10000 });
    assert.equal(await readFile(filmPath, 'utf8'), filmAfterDrop);
    assert.equal(await readFile(analysisPath, 'utf8'), beforeAnalysis);
    await axis.getByRole('button', { name: '显示完整原片' }).click();
    assert.deepEqual(await grayRange(), grayExpanded, 'zoom preserves adjusted gray range');
    await gray.hover();
    await page.evaluate(() => { const label = document.createElement('div'); label.textContent = '合成测试·上方拉边'; Object.assign(label.style, { position:'fixed', top:'4px', right:'8px', zIndex:'99999', background:'#fff', color:'#111', padding:'3px 8px', fontSize:'12px' }); document.body.appendChild(label); });
    await page.screenshot({ path: resolve('../../.tmp/source-upper-trim-verified.png') });
    step = 'drop adjusted gray range';
    const grayBox = await gray.boundingBox(), filmTarget = await filmBlock.boundingBox(); assert.ok(grayBox && filmTarget);
    const hit = await page.evaluate(({ x, y }) => { const el = document.elementFromPoint(x, y); return { tag: el?.tagName, gray: el?.closest('[data-source-context]')?.getAttribute('data-source-context'), candidate: el?.closest('[data-source-candidate]')?.getAttribute('data-source-candidate') }; }, { x: grayBox.x + grayBox.width / 2, y: grayBox.y + grayBox.height / 2 });
    assert.equal(hit.gray, '19500:22000', `gray must be hit before drag: ${JSON.stringify(hit)}`);
    await page.mouse.move(grayBox.x + grayBox.width / 2, grayBox.y + grayBox.height / 2); await page.mouse.down();
    const targetScroll = await dock.locator('.tl-scroll').boundingBox(); assert.ok(targetScroll);
    await page.mouse.move(targetScroll.x + targetScroll.width - 20, filmTarget.y + filmTarget.height / 2, { steps: 30 }); await page.waitForTimeout(300);
    await page.mouse.up();
    await page.waitForTimeout(1800);
    const filmAfterGray = await readFile(filmPath, 'utf8');
    assert.ok(filmAfterGray.includes(`synthetic-a.mp4#t=${grayExpanded.start / 1000},${grayExpanded.end / 1000}`), `gray drop preserves adjusted source range ${JSON.stringify(grayExpanded)}`);
    await gray.locator('[data-source-trim="end"]').dblclick();
    assert.deepEqual(await grayRange(), { start: 19500, end: 22000 });
    assert.equal(await readFile(filmPath, 'utf8'), filmAfterGray);
    assert.equal(await readFile(analysisPath, 'utf8'), beforeAnalysis);
  } catch (error) { throw new Error(`Synthetic source range test failed at: ${step}`, { cause: error }); }
  finally {
    await browser?.close(); await studio?.close();
    for (const [k, v] of Object.entries(oldEnv)) { if (v === undefined) delete process.env[k]; else process.env[k] = v; }
    await rm(scratch, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 });
  }
});

