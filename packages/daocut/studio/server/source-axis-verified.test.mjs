import { test } from 'node:test';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { chromium } from 'playwright-core';
import { startStudio } from './server.mjs';
import { filmHtml } from '../../src/film-doc.mjs';

test('source axis with isolated synthetic media', { timeout: 120000 }, async () => {
  const base = resolve('../../.tmp'); await mkdir(base, { recursive: true });
  const scratch = await mkdtemp(join(base, 'source-axis-verified-'));
  const oldEnv = Object.fromEntries(['DAOCUT_STUDIO_HOME', 'DAOCUT_LIBRARY', 'DAOCUT_TRASH_DIR'].map(k => [k, process.env[k]]));
  process.env.DAOCUT_STUDIO_HOME = join(scratch, 'home'); process.env.DAOCUT_LIBRARY = join(scratch, 'library'); process.env.DAOCUT_TRASH_DIR = join(scratch, 'trash');
  await mkdir(process.env.DAOCUT_TRASH_DIR);
  let studio, browser, step = 'setup';
  try {
    studio = await startStudio({ port: 0, openBrowser: () => {} });
    const api = async (path, method = 'GET', body) => {
      const r = await fetch(`${studio.origin}${path}`, { method, headers: { 'x-studio-key': studio.key, ...(body ? { 'content-type': 'application/json' } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
      assert.equal(r.status, 200, 'fixture API failed'); return r.json();
    };
    const { project } = await api('/api/projects', 'POST', { path: join(scratch, 'synthetic-project') });
    await mkdir(join(project.path, 'assets'), { recursive: true });
    for (const name of ['a', 'b']) execFileSync('ffmpeg', ['-v', 'error', '-f', 'lavfi', '-i', 'testsrc2=s=320x180:r=10:d=30', '-f', 'lavfi', '-i', 'sine=frequency=440:duration=30', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-c:a', 'aac', '-shortest', '-y', join(project.path, 'assets', `synthetic-${name}.mp4`)], { windowsHide: true });
    const tags = ['钩子', '痛点', '卖点', '产品演示', '价格锚点', '行动指令'];
    const starts = [1000, 4000, 7000, 10000, 17000, 22000];
    const analysis = { version: 1, sources: ['a', 'b'].map(id => ({ id, assetPath: `assets/synthetic-${id}.mp4`, durationMs: null })), products: [{ id: 'p', name: '合成测试商品', sourceIds: ['a', 'b'] }], intervals: [{ id: 'i', productId: 'p', sourceId: 'a', startMs: 0, endMs: 29000 }, { id: 'j', productId: 'p', sourceId: 'b', startMs: 15000, endMs: 29000 }], candidates: [...tags.map((tag, n) => ({ id: `c${n}`, productId: 'p', intervalId: 'i', sourceId: 'a', startMs: starts[n], endMs: starts[n] + 2500, text: `合成${tag}`, tags: [tag], origin: 'synthetic-test', version: 1 })), { id: 'multi', productId: 'p', intervalId: 'i', sourceId: 'a', startMs: 12000, endMs: 16000, text: '合成多标签', tags: ['钩子', '痛点'], origin: 'synthetic-test', version: 1 }, { id: 'other', productId: 'p', intervalId: 'j', sourceId: 'b', startMs: 20000, endMs: 23000, text: '合成切换来源', tags: ['行动指令'], origin: 'synthetic-test', version: 1 }] };
    await api(`/api/projects/${project.id}/product-analysis`, 'PUT', { analysis });
    const filmPath = join(project.path, 'film.html');
    await writeFile(filmPath, filmHtml({ stage: { w: 320, h: 180 }, tracks: [{ clips: [{ id: 'synthetic-clip', src: 'assets/synthetic-a.mp4', at: 0, time: [0, 2] }] }] }));
    const before = await readFile(filmPath, 'utf8');
    const analysisPath = join(project.path, '.film', 'product-analysis.json');
    const beforeAnalysis = await readFile(analysisPath, 'utf8');
    const mediaPath = join(project.path, 'assets', 'synthetic-b.mp4');
    const hash = async () => createHash('sha256').update(await readFile(mediaPath)).digest('hex');
    const beforeHash = await hash();
    const hashA = async () => createHash('sha256').update(await readFile(join(project.path, 'assets', 'synthetic-a.mp4'))).digest('hex');
    const beforeHashA = await hashA();
    browser = await chromium.launch({ executablePath: process.env.DAOCUT_TEST_BROWSER || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
    const page = await browser.newPage({ viewport: { width: 1600, height: 1050 } });
    await page.route('**/live-analysis**', route => route.fulfill({ json: { transcription: { status: 'idle', segments: [] }, analysis: { status: 'idle' } } }));
    step = 'open synthetic project';
    await page.goto(`${studio.origin}/projects/${project.id}?key=${studio.key}`);
    await page.getByRole('button', { name: '商品与结构' }).click();
    await page.getByRole('button', { name: '合成测试商品' }).first().waitFor();
    const axis = page.locator('[data-source-axis]'); await axis.waitFor();
    step = 'thumbnail and waveform';
    await axis.getByLabel('原片视频缩略帧').locator('img').first().waitFor({ timeout: 30000 });
    await page.waitForFunction(() => [...document.querySelectorAll('[data-source-axis] [aria-label="原片视频缩略帧"] img')].some(i => i.complete && i.naturalWidth > 0 && getComputedStyle(i).visibility !== 'hidden'), null, { timeout: 30000 });
    await page.waitForFunction(() => { const c = document.querySelector('[data-source-axis] [aria-label="原片音频波形"] canvas'); if (!c || !c.width || !c.height) return false; return [...c.getContext('2d').getImageData(0, 0, c.width, c.height).data].some((v, i) => i % 4 === 3 && v > 0); }, null, { timeout: 30000 });
    step = 'ruler and structure colors';
    const ruler = axis.getByLabel('原片时间位置'); assert.ok(await ruler.locator('span').count() > 1); assert.ok(await ruler.getByText('00:00', { exact: true }).count());
    step = 'structure controls'; const track = axis.getByLabel('结构轨道');
    const candidate = id => track.locator(`[data-source-candidate="${id}"]`);
    const filmBlock = page.locator('[data-timeline-scope=main] [data-block-kind=video]').first();
    await filmBlock.waitFor();
    assert.ok(Math.abs((await candidate('c0').boundingBox()).height - (await filmBlock.boundingBox()).height) <= 2);
    await page.waitForFunction(() => [...document.querySelectorAll('[data-source-candidate="c0"] img')].some(i => i.complete && i.naturalWidth > 0), null, { timeout: 30000 });
    await page.waitForFunction(() => { const c = document.querySelector('[data-source-candidate="c0"] canvas'); return c && c.width && c.height && [...c.getContext('2d').getImageData(0, 0, c.width, c.height).data].some((v, i) => i % 4 === 3 && v > 0); }, null, { timeout: 30000 });
    const backgrounds = [];
    for (let n = 0; n < tags.length; n++) backgrounds.push(await candidate(`c${n}`).locator('[data-structure-colors]').evaluate(el => getComputedStyle(el).backgroundImage));
    step = 'six distinct colors'; assert.equal(new Set(backgrounds).size, 6);
    step = 'multiple tag color stops'; const multi = await candidate('multi').locator('[data-structure-colors]').evaluate(el => getComputedStyle(el).backgroundImage);
    assert.match(multi, /rgb\(219, 234, 254\)/); assert.match(multi, /rgb\(255, 237, 213\)/);
    assert.match(await candidate('multi').getAttribute('aria-label'), /钩子.*痛点/);
    await mkdir(resolve('../../.tmp'), { recursive: true });
    await page.locator('[data-timeline-scope=main] [data-block-kind=video]').first().waitFor();
    await page.evaluate(() => { const label = document.createElement('div'); label.textContent = '合成测试画面 · 非真实工程'; Object.assign(label.style, { position: 'fixed', top: '4px', right: '8px', zIndex: '99999', background: '#fff', color: '#111', padding: '3px 8px', fontSize: '12px' }); document.body.appendChild(label); });
    await page.screenshot({ path: resolve('../../.tmp/source-segments-verified.png') });
    step = 'overlapping selection';
    const first = track.getByRole('button', { name: '钩子｜合成钩子' }); const second = track.getByRole('button', { name: '痛点｜合成痛点' });
    assert.notEqual((await candidate('c3').boundingBox()).y, (await candidate('multi').boundingBox()).y);
    await first.click(); await page.waitForFunction(() => [...document.querySelectorAll('video')].some(v => v.currentTime >= 1 && v.currentTime < 2));
    await second.click(); await page.waitForFunction(() => [...document.querySelectorAll('video')].some(v => v.currentTime >= 4 && v.currentTime < 5));
    assert.equal(await readFile(filmPath, 'utf8'), before, 'click only seeks');
    const idsBeforeFilter = await track.locator('[data-source-candidate]').evaluateAll(els => els.map(el => el.getAttribute('data-source-candidate')).sort());
    await page.getByRole('button', { name: /^钩子\s+\d+$/ }).click();
    assert.deepEqual(await track.locator('[data-source-candidate]').evaluateAll(els => els.map(el => el.getAttribute('data-source-candidate')).sort()), idsBeforeFilter);
    assert.equal(await candidate('c0').getAttribute('data-highlighted'), 'true');
    assert.equal(await candidate('c1').getAttribute('data-highlighted'), 'false');
    assert.equal(await readFile(filmPath, 'utf8'), before, 'filter does not write film');
    step = 'zoom and scroll';
    for (let i = 0; i < 4; i++) await axis.getByRole('button', { name: '放大时间轴' }).click();
    const scroll = axis.locator('.overflow-auto'); assert.ok(await scroll.evaluate(el => el.scrollWidth > el.clientWidth));
    await scroll.evaluate(el => { el.scrollLeft = el.scrollWidth; }); assert.ok(await scroll.evaluate(el => el.scrollLeft > 0));
    await axis.getByRole('button', { name: '显示完整原片' }).click(); assert.equal(await scroll.evaluate(el => el.scrollLeft), 0);
    for (let i = 0; i < 3; i++) await axis.getByRole('button', { name: '放大时间轴' }).click();
    assert.ok(Number(await axis.getByLabel('原片时间轴缩放').inputValue()) > 0);
    step = 'source switch and seek';
    await page.getByRole('button', { name: /^行动指令\s+\d+$/ }).click();
    await page.getByLabel('候选片段').getByText('合成切换来源').click();
    await page.waitForFunction(() => [...document.querySelectorAll('video')].some(v => v.currentSrc.includes('synthetic-b.mp4') && v.currentTime >= 20 && v.currentTime < 21.5));
    await page.waitForFunction(() => [...document.querySelectorAll('[data-source-axis] [aria-label="原片视频缩略帧"] img')].some(i => i.complete && i.naturalWidth > 0), null, { timeout: 30000 });
    assert.equal(Number(await axis.getByLabel('原片时间轴缩放').inputValue()), 0, 'source switch resets zoom');
    assert.equal(await readFile(filmPath, 'utf8'), before);
    step = 'drag cross-source candidate to film';
    const dock = page.locator('[data-timeline-scope="main"]');
    const magnet = dock.locator('[data-timeline-magnet]');
    if ((await magnet.getAttribute('data-timeline-magnet')) === '1') await magnet.locator('button').click();
    const bb = await filmBlock.boundingBox(), scrollBox = await dock.locator('.tl-scroll').boundingBox();
    const sourceBox = await candidate('other').boundingBox();
    assert.ok(bb && scrollBox && sourceBox);
    const x = Math.min(scrollBox.x + scrollBox.width - 20, bb.x + bb.width + 180);
    await page.mouse.move(sourceBox.x + sourceBox.width / 2, sourceBox.y + sourceBox.height / 2);
    await page.mouse.down();
    await page.mouse.move(x, bb.y + bb.height / 2, { steps: 30 });
    await page.waitForTimeout(300);
    assert.equal(await readFile(filmPath, 'utf8'), before, 'drag preview does not write');
    await page.mouse.up();
    await page.waitForTimeout(1800);
    const after = await readFile(filmPath, 'utf8');
    assert.match(after, /assets\/synthetic-a\.mp4#t=0,2/, 'existing clip retained');
    assert.match(after, /assets\/synthetic-b\.mp4#t=20,23/, 'cross-source bounds retained');
    step = 'extend candidate edges';
    const added = dock.locator('[data-block-kind="video"]').last();
    const dragEdge = async (edge, dx) => {
      const handle = added.locator(`[data-trim="${edge}"]`); await handle.scrollIntoViewIfNeeded();
      const box = await handle.boundingBox(); assert.ok(box);
      await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
      await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + dx, box.y + box.height / 2, { steps: 20 }); await page.mouse.up();
      await page.waitForTimeout(1400);
    };
    const bounds = async () => (await readFile(filmPath, 'utf8')).match(/synthetic-b\.mp4#t=([\d.]+),([\d.]+)/)?.slice(1).map(Number);
    await dragEdge('start', -30);
    const left = await bounds(); assert.ok(left && left[0] < 20 && left[1] === 23, `left extension restores earlier source: ${JSON.stringify(left)}`);
    await dragEdge('end', 30);
    const right = await bounds(); assert.ok(right && right[0] < 20 && right[1] > 23, `right extension restores later source: ${JSON.stringify(right)}`);
    assert.equal(await readFile(analysisPath, 'utf8'), beforeAnalysis);
    assert.equal(await hash(), beforeHash);
    const finalFilm = await readFile(filmPath, 'utf8');
    await page.reload();
    await page.waitForTimeout(1200);
    assert.equal(await readFile(filmPath, 'utf8'), finalFilm, 'drop and trim survive reload');
    step = 'gray source context seeks without writing';
    await page.getByRole('button', { name: '商品与结构' }).click();
    await page.getByRole('button', { name: '合成测试商品' }).first().waitFor();
    await page.getByLabel('候选片段').getByText('合成钩子', { exact: true }).click();
    await page.waitForFunction(() => [...document.querySelectorAll('video')].some(v => v.currentSrc.includes('synthetic-a.mp4')));
    const gray = axis.locator('[data-source-context="19500:22000"]');
    await gray.waitFor();
    assert.equal(await gray.getAttribute('draggable'), 'true');
    assert.equal(await gray.getAttribute('data-start-ms'), '19500');
    assert.equal(await gray.getAttribute('data-end-ms'), '22000');
    assert.equal(await gray.locator('[data-structure-colors]').count(), 0, 'context has no invented analysis labels');
    await gray.click();
    await page.waitForFunction(() => [...document.querySelectorAll('video')].some(v => v.currentSrc.includes('synthetic-a.mp4') && v.currentTime >= 19.5 && v.currentTime <= 22));
    assert.equal(await readFile(filmPath, 'utf8'), finalFilm, 'gray click only seeks');
    const overlapGray = axis.locator('[data-source-context="12500:17000"]');
    await overlapGray.waitFor();
    assert.equal(await overlapGray.getAttribute('draggable'), 'true');
    assert.ok(await candidate('multi').count(), 'overlapping candidate remains on another row');
    await axis.getByRole('button', { name: '放大时间轴' }).click();
    assert.equal(await gray.getAttribute('data-start-ms'), '19500', 'zoom preserves source coordinates');
    assert.equal(await gray.getAttribute('data-end-ms'), '22000', 'zoom preserves source coordinates');
    await axis.getByRole('button', { name: '显示完整原片' }).click();
    await page.evaluate(() => { const label = document.createElement('div'); label.textContent = '合成测试画面 · 非真实工程'; Object.assign(label.style, { position: 'fixed', top: '4px', right: '8px', zIndex: '99999', background: '#fff', color: '#111', padding: '3px 8px', fontSize: '12px' }); document.body.appendChild(label); });
    await page.screenshot({ path: resolve('../../.tmp/source-gray-range-verified.png') });

    step = 'drag and extend gray source context';
    const grayBox = await gray.boundingBox();
    const lastBox = await dock.locator('[data-block-kind="video"]').last().boundingBox();
    const dockScrollBox = await dock.locator('.tl-scroll').boundingBox();
    assert.ok(grayBox && lastBox && dockScrollBox);
    const grayX = Math.min(dockScrollBox.x + dockScrollBox.width - 20, lastBox.x + lastBox.width + 100);
    await page.mouse.move(grayBox.x + grayBox.width / 2, grayBox.y + grayBox.height / 2);
    await page.mouse.down(); await page.mouse.move(grayX, lastBox.y + lastBox.height / 2, { steps: 30 });
    await page.waitForTimeout(300);
    assert.equal(await readFile(filmPath, 'utf8'), finalFilm, 'gray drag preview does not write');
    await page.mouse.up(); await page.waitForTimeout(1800);
    assert.match(await readFile(filmPath, 'utf8'), /assets\/synthetic-a\.mp4#t=19\.5,22/, 'gray drop preserves source bounds');
    const grayAdded = dock.locator('[data-block-kind="video"]').last();
    const grayBounds = async () => (await readFile(filmPath, 'utf8')).match(/synthetic-a\.mp4#t=([\d.]+),([\d.]+)(?![\s\S]*synthetic-a\.mp4#t=)/)?.slice(1).map(Number);
    const grayEdge = async (edge, dx) => {
      const handle = grayAdded.locator(`[data-trim="${edge}"]`); await handle.scrollIntoViewIfNeeded();
      const box = await handle.boundingBox(); assert.ok(box);
      await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
      await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + dx, box.y + box.height / 2, { steps: 20 }); await page.mouse.up();
      await page.waitForTimeout(1400);
    };
    await grayEdge('start', -30);
    const grayLeft = await grayBounds(); assert.ok(grayLeft && grayLeft[0] < 19.5 && grayLeft[1] === 22, `gray left extension: ${JSON.stringify(grayLeft)}`);
    await grayEdge('end', 30);
    const grayRight = await grayBounds(); assert.ok(grayRight && grayRight[0] < 19.5 && grayRight[1] > 22, `gray right extension: ${JSON.stringify(grayRight)}`);
    assert.equal(await readFile(analysisPath, 'utf8'), beforeAnalysis);
    assert.equal(await hash(), beforeHash); assert.equal(await hashA(), beforeHashA);

    step = 'empty candidates retain draggable full source';
    await api(`/api/projects/${project.id}/product-analysis`, 'PUT', { analysis: { ...analysis, candidates: [] } });
    await page.reload();
    await page.getByRole('button', { name: '商品与结构' }).click();
    const fullGray = axis.locator('[data-source-context="0:30000"]');
    await fullGray.waitFor();
    assert.equal(await fullGray.getAttribute('draggable'), 'true');
  } catch (error) { throw new Error(`Synthetic source axis test failed at: ${step}`, { cause: error }); }
  finally {
    await browser?.close(); await studio?.close();
    for (const [k, v] of Object.entries(oldEnv)) { if (v === undefined) delete process.env[k]; else process.env[k] = v; }
    await rm(scratch, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 });
  }
});




