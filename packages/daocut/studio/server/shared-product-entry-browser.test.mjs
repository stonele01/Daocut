import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdir, mkdtemp, readFile, writeFile} from 'node:fs/promises';
import {join, resolve} from 'node:path';
import {execFileSync} from 'node:child_process';
import {chromium} from 'playwright-core';
import {startStudio} from './server.mjs';
import {ensureStructureDraft} from './structure-drafts.mjs';
import {writeProjectFilm} from './film.mjs';

test('an old partial reader refreshes once and the ordinary product button opens exact saved plans', {timeout: 60000}, async () => {
  const base=resolve(import.meta.dirname,'../../../../.tmp/shared-product-entry-browser');
  await mkdir(base,{recursive:true}); const scratch=await mkdtemp(join(base,'case-'));
  const env=['DAOCUT_STUDIO_HOME','DAOCUT_LIBRARY','DAOCUT_TRASH_DIR','DAOCUT_NO_UPDATE_CHECK'];
  const before=Object.fromEntries(env.map(k=>[k,process.env[k]]));
  Object.assign(process.env,{DAOCUT_STUDIO_HOME:join(scratch,'home'),DAOCUT_LIBRARY:join(scratch,'library'),DAOCUT_TRASH_DIR:join(scratch,'trash'),DAOCUT_NO_UPDATE_CHECK:'1'});
  await mkdir(process.env.DAOCUT_TRASH_DIR);
  let studio,browser,page;
  try {
    studio=await startStudio({port:0,openBrowser:()=>{},...(process.env.DAOCUT_STRUCTURE_UI?{editorDir:resolve(process.env.DAOCUT_STRUCTURE_UI)}:{})});
    const api=async(path,method='GET',body)=>{const r=await fetch(studio.origin+path,{method,headers:{'x-studio-key':studio.key,'content-type':'application/json'},...(body?{body:JSON.stringify(body)}:{})});const result=await r.json();assert.equal(r.status,200,JSON.stringify(result));return result;};
    const {project}=await api('/api/projects','POST',{path:join(scratch,'project')});
    await mkdir(join(project.path,'assets'),{recursive:true});
    const assetPath='assets/synthetic.mp4';
    execFileSync('ffmpeg',['-v','error','-f','lavfi','-i','color=c=blue:s=96x160:r=10:d=16','-c:v','libx264','-pix_fmt','yuv420p','-y',join(project.path,assetPath)],{windowsHide:true});
    const scope={sourceId:'s',productId:'p',intervalId:'i',startMs:0,endMs:16000};
    const clips=[{candidateId:'h',sourceId:'s',assetPath,startMs:0,endMs:2000,text:'合成开头',roles:['hook'],coreIds:[]},{candidateId:'core',sourceId:'s',assetPath,startMs:4000,endMs:7000,text:'合成卖点',roles:['core'],coreIds:['core']}];
    const plan={id:'synthetic-plan',version:1,scope,speed:1,durationMs:5000,coreIds:['core'],coreLabels:{core:'合成卖点'},clips};
    const analysis={version:1,sources:[{id:'s',assetPath,durationMs:16000}],products:[{id:'p',name:'合成商品',sourceIds:['s']}],intervals:[{id:'i',sourceId:'s',productId:'p',startMs:0,endMs:16000}],candidates:clips.map((c,i)=>({...c,id:c.candidateId,productId:'p',intervalId:'i',cueRange:[i,i],tags:[i?'卖点':'钩子'],origin:'synthetic-test',version:1}))};
    await api(`/api/projects/${project.id}/product-analysis`,'PUT',{analysis});
    await writeProjectFilm(project.path,{stage:{w:96,h:160},tracks:[{clips:[{id:'parent',src:assetPath,time:[14,15],at:0}]}]});
    await writeFile(join(project.path,'assets/synthetic.vtt'),'WEBVTT\n\n00:00:00.000 --> 00:00:02.000\n合成字幕\n');
    const draft=await ensureStructureDraft(project.path,{parentProjectId:project.id,plan});
    await writeProjectFilm(draft.root,{stage:{w:96,h:160},tracks:[{clips:[{id:'personal-edit',src:assetPath,time:[4.2,6.5],at:0}]}]});
    const files=[join(project.path,'film.html'),join(project.path,'.film/product-analysis.json'),join(draft.root,'film.html'),join(draft.root,'assets/synthetic.vtt')];
    const originals=await Promise.all(files.map(p=>readFile(p,'utf8')));
    const errors=[],paid=[],reads=[]; let resumed=0;
    const restored={...analysis,products:[...analysis.products,{id:'saved',name:'已有拼结构 0–16秒',sourceIds:['s']}],candidates:[],
      scopes:[{id:'saved-range',productId:'saved',sourceId:'s',startMs:0,endMs:16000,kind:'historical-analysis',confirmed:true,origin:'shared-composition',joinedScopeIds:['a','b'],analysisRevision:'a'.repeat(64)}, ...[{id:'a',startMs:0,endMs:8000},{id:'b',startMs:8000,endMs:16000}].map(r=>({...r,productId:'saved',sourceId:'s',kind:'historical-analysis',confirmed:true,origin:'shared-historical'}))]};
    restored.intervals = restored.intervals.map(r => ({...r, savedResultScopeId: 'saved-range'}));
    restored.products.find(p => p.id === 'saved').sharedLayoutHidden = true;
    restored.candidates=analysis.candidates.map(c=>({...c,productId:'saved',intervalId:'a'}));
    restored.products.push({id:'unmatched',name:'已有话术（商品待核对） 12–15秒',sourceIds:['s']});
    restored.scopes.push({id:'unmatched-range',sourceId:'s',productId:'unmatched',startMs:12000,endMs:15000,kind:'historical-analysis',confirmed:true,origin:'shared-historical'});
    restored.candidates.push({...analysis.candidates[0],id:'unmatched-quote',productId:'unmatched',intervalId:'unmatched-range',startMs:12000,endMs:14000,text:'未匹配原话'});
    let releasePlans; const plansGate=new Promise(resolve=>{releasePlans=resolve;});
    await api(`/api/projects/${project.id}/product-analysis`,'PUT',{analysis:{...analysis,candidates:[]}});
    browser=await chromium.launch({executablePath:process.env.DAOCUT_TEST_BROWSER||'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
    page=await browser.newPage({viewport:{width:1680,height:1050}});page.setDefaultTimeout(15000);
    page.on('pageerror',e=>errors.push(e.message));
    await page.route('**/*',route=>{const r=route.request(),u=new URL(r.url());if(![studio.origin,studio.filmOrigin].includes(u.origin))return route.abort();if(r.method()==='POST'&&/\/(?:live-analysis|product-workflow|product-discovery|turns|exports)(?:\/|$)/.test(u.pathname)){paid.push(u.pathname);return route.fulfill({status:409,json:{error:'disabled in fixture'}});}return route.continue();});
    const report={status:'review-required',imported:{transcription:0,discovery:0,analysis:0},requestCount:0,warnings:['旧读取未完成']};
    await page.route('**/product-workflow/shared-open',route=>route.fulfill({json:{sharedRead:resumed?{...report,readerRevision:3,warnings:[]}:report}}));
    await page.route('**/product-workflow/resume-shared',async route=>{
      resumed++;assert.deepEqual(route.request().postDataJSON(),{sourceId:'s',confirmed:true});
      await api(`/api/projects/${project.id}/product-analysis`,'PUT',{analysis:restored});
      return route.fulfill({json:{...report,readerRevision:3,status:'ready',warnings:[],skippedRecords:0,failedRecords:0}});
    });
    await page.route('**/live-analysis**',route=>route.fulfill({json:{transcription:{status:'complete',segments:[]},analysis:{status:'idle'}}}));
    await page.route('**/structure-plans**',async route=>{
      assert.equal(route.request().method(),'GET');const q=new URL(route.request().url()).searchParams;reads.push(Object.fromEntries(q));
      const matched=q.get('intervalId')==='saved-range'&&q.get('productId')==='saved';
      if(matched)await plansGate;
      return route.fulfill({json:{status:matched?'complete':'unavailable',taskKey:'existing-shared-key',context:{...scope,visibility:'shared'},plans:matched?[{...plan,scope:{...scope,productId:'saved',intervalId:'saved-range'}}]:[],complete:matched,generationMethod:'ai',issues:[],requestCount:0}});
    });
    await page.goto(`${studio.origin}/projects/${project.id}?key=${studio.key}`);
    await page.getByRole('button',{name:'商品与结构',exact:true}).click();
    await page.getByText('已读取已有分析，可直接预览和选材',{exact:true}).waitFor();
    const card=page.locator('[data-product-card="p"]');
    await card.getByRole('button',{name:/^合成商品/}).click();
    await card.getByText('2 条话术',{exact:true}).waitFor();
    await card.getByRole('button',{name:'查看已有分析',exact:true}).click();
    await page.getByRole('button',{name:'卖点 1',exact:true}).click();
    assert.equal(await page.locator('[data-candidate-card]').count(),1);
    await page.locator('[data-source-candidate="core"][data-source-highlighted="true"]').waitFor();
    assert.equal(await page.locator('[data-source-candidate="h"][data-source-highlighted="true"]').count(),0);
    await card.getByRole('button',{name:'查看已有分析',exact:true}).click();
    assert.equal(await page.locator('[data-candidate-card]').count(),2);
    assert.equal(await page.locator('[data-product-card="saved"]').count(),0,'matched recovery is represented by the named product');
    assert.equal(await page.locator('[data-product-card="unmatched"]').count(),0,'unmatched records do not clutter the product list');
    await card.getByRole('button',{name:'拼结构',exact:true}).click();
    await page.getByText('正在读取已有方案…',{exact:true}).waitFor();
    releasePlans();
    await page.getByRole('checkbox',{name:'选择方案 1 导出',exact:true}).waitFor();
    await page.getByRole('button',{name:'待确认的已有分析 1',exact:true}).click();
    await page.locator('[data-product-card="unmatched"]').getByRole('button',{name:/^已有分析/}).click();
    await page.getByText('未匹配原话',{exact:true}).waitFor();
    await page.getByRole('button',{name:'返回商品列表',exact:true}).click();
    await page.getByRole('button',{name:'卖点 1',exact:true}).waitFor();
    assert.equal(await page.locator('[data-product-card="unmatched"]').count(),0);
    await page.getByRole('button',{name:'待确认的已有分析 1',exact:true}).click();
    const unmatched=page.locator('[data-product-card="unmatched"]');
    await unmatched.getByRole('button',{name:/^已有分析/}).click();
    await unmatched.getByRole('button',{name:/^编辑商品名称/}).click();
    await page.getByRole('textbox',{name:'商品名称',exact:true}).fill('人工确认的商品');
    await unmatched.getByRole('button',{name:'保存',exact:true}).click();
    await unmatched.getByRole('button',{name:/^人工确认的商品/}).waitFor();
    await page.getByText('未匹配原话',{exact:true}).waitFor();
    assert.equal(await page.getByRole('button',{name:/待确认的已有分析/}).count(),0);
    await card.getByRole('button',{name:/^合成商品/}).click();
    await page.getByRole('button',{name:'卖点 1',exact:true}).waitFor();
    assert.equal(resumed,1);assert.ok(reads.some(r=>r.intervalId==='saved-range'&&!r.taskKey&&!r.rulesVersion));
    assert.deepEqual(await Promise.all([files[0],files[2],files[3]].map(p=>readFile(p,'utf8'))),[originals[0],originals[2],originals[3]]);
    assert.deepEqual(paid,[]);assert.deepEqual(errors,[]);
    await writeFile(join(base,'result.json'),JSON.stringify({passed:true,modelRequests:0,oldReaderRepaired:true,ordinaryProductEntry:true,privateEditsPreserved:true,resumed},null,2));
  } catch(e){await page?.screenshot({path:join(base,'failure.png')}).catch(()=>{});throw e;}
  finally {await browser?.close();await studio?.close();for(const [k,v]of Object.entries(before)){if(v===undefined)delete process.env[k];else process.env[k]=v;}}
});
