import { test } from 'node:test';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdir, mkdtemp, readFile, rm } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { chromium } from 'playwright-core';
import { startStudio } from './server.mjs';

test('synthetic browser acceptance', { timeout: 90000 }, async () => {
  const base = resolve('.test-temp'); await mkdir(base, { recursive: true });
  const scratch = await mkdtemp(join(base, 'product-browser-'));
  process.env.DAOCUT_STUDIO_HOME = join(scratch, 'home'); process.env.DAOCUT_LIBRARY = join(scratch, 'library'); process.env.DAOCUT_TRASH_DIR = join(scratch, 'trash');
  await mkdir(process.env.DAOCUT_TRASH_DIR);
  let studio, browser;
  try {
    studio = await startStudio({ port: 0, openBrowser: () => {} });
    const api = async (path, method = 'GET', body) => { const res = await fetch(`${studio.origin}${path}`, { method, headers: { 'x-studio-key': studio.key, ...(body ? { 'content-type': 'application/json' } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) }); const value = await res.json(); assert.equal(res.status, 200, JSON.stringify(value)); return value; };
    const { project } = await api('/api/projects', 'POST', { path: join(scratch, 'synthetic-project') });
    await mkdir(join(project.path, 'assets'), { recursive: true });
    for (const name of ['synthetic-a.mp4', 'synthetic-b.mp4']) execFileSync('ffmpeg', ['-v', 'error', '-f', 'lavfi', '-i', 'color=c=blue:s=64x64:r=10:d=12', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-y', join(project.path, 'assets', name)], { windowsHide: true });
    const tags = ['钩子', '痛点', '卖点', '产品演示', '价格锚点', '行动指令'];
    const analysis = { version: 1, sources: [{ id: 'a', assetPath: 'assets/synthetic-a.mp4', durationMs: null }, { id: 'b', assetPath: 'assets/synthetic-b.mp4', durationMs: null }], products: [{ id: 'p1', name: '虚构示例甲', sourceIds: ['a', 'b'] }, { id: 'p2', name: '虚构示例乙', sourceIds: ['a', 'b'] }], intervals: [{ id: 'i1', productId: 'p1', sourceId: 'a', startMs: 0, endMs: 5000 }, { id: 'i2', productId: 'p1', sourceId: 'b', startMs: 4000, endMs: 9000 }, { id: 'i3', productId: 'p1', sourceId: 'a', startMs: 7000, endMs: 9000 }, { id: 'i4', productId: 'p2', sourceId: 'a', startMs: 9500, endMs: 11000 }], candidates: tags.map((tag, n) => ({ id: `c${n}`, productId: 'p1', intervalId: n === 5 ? 'i2' : 'i1', sourceId: n === 5 ? 'b' : 'a', startMs: n === 5 ? 6000 : 1000 + n * 100, endMs: n === 5 ? 8000 : 3000 + n * 100, text: `虚构样例${tag}`, tags: [tag], origin: 'synthetic-test', version: 1 })) };
    analysis.products.push({ id: 'p3', name: '虚构示例丙（未分析）', sourceIds: ['b'] });
    analysis.intervals.push({ id: 'i5', productId: 'p3', sourceId: 'b', startMs: 9000, endMs: 11000 });
    await api(`/api/projects/${project.id}/product-analysis`, 'PUT', { analysis });
    browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
    const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
    await page.goto(`${studio.origin}/projects/${project.id}?key=${studio.key}`);
    await page.getByRole('button', { name: '商品与结构' }).click();
    await page.getByRole('button', { name: '虚构示例甲' }).first().waitFor();
    assert.equal(await page.getByText('管理当前商品', { exact: true }).count(), 0);
    assert.equal(await page.getByText('管理来源视频', { exact: true }).count(), 0);
    assert.equal(await page.getByRole('button', { name: '新增商品', exact: true }).count(), 0);
    assert.equal(await page.getByRole('button', { name: '恢复上次', exact: true }).count(), 0);
    assert.equal(await page.getByText(/^编辑商品范围/).count(), 0);
    const filmPath = join(project.path, 'film.html');
    const analysisPath = join(project.path, '.film', 'product-analysis.json');
    const beforeFilm = await readFile(filmPath, 'utf8');
    const beforeAnalysis = await readFile(analysisPath, 'utf8');
    const requests = [];
    page.on('request', request => requests.push({ url: request.url(), method: request.method() }));
    await page.getByRole('button', { name: '如何开始分析' }).click();
    assert.ok(await page.getByText('后续将从当前直播原片开始分析，识别商品和结构片段；目前自动分析尚未接入，可先人工整理或查看示例。').isVisible());
    assert.equal(requests.length, 0, 'AI entry must not make requests');
    assert.equal(await readFile(filmPath, 'utf8'), beforeFilm);
    assert.equal(await readFile(analysisPath, 'utf8'), beforeAnalysis);
    const sourceDock = page.locator('[data-source-timeline-dock]');
    const filmDock = page.locator('[data-timeline-scope="main"]');
    assert.ok(await sourceDock.isVisible());
    assert.ok(await filmDock.isVisible());
    const sourceBox = await sourceDock.boundingBox(), filmBox = await filmDock.boundingBox();
    assert.ok(sourceBox && filmBox && sourceBox.y < filmBox.y);
    await filmDock.click({ position: { x: 40, y: 40 } });
    assert.ok(await sourceDock.isVisible());
    assert.equal(await readFile(filmPath, 'utf8'), beforeFilm);
    const projectCountBeforeDemo = (await api('/api/projects')).projects.length;
    for (let n = 0; n < 2; n++) {
      await page.getByRole('button', { name: '查看示例' }).click();
      await page.getByText('演示模式 · 内容与视频均为合成示例').waitFor();
      if (n === 0) {
        for (const label of ['演示洁面（演示数据）', '演示精华（演示数据）', '演示面霜（演示数据）', '演示商品（尚未分析）']) await page.getByLabel('商品列表').getByRole('button', { name: label }).first().waitFor();
        await page.getByText('原片时间轴').waitFor();
        await page.waitForFunction(() => [...document.querySelectorAll('video')].some(video => video.currentSrc.includes('demo-source-a.mp4') && video.readyState >= 1 && video.duration === 12));
        await page.locator('video').first().evaluate(video => { video.currentTime = 1; return video.play(); });
        await page.waitForFunction(() => [...document.querySelectorAll('video')].some(video => video.currentTime > 1.1 && !video.paused));
        await page.locator('video').first().evaluate(video => video.pause());
        await page.getByLabel('原片时间位置').press('End');
        await page.waitForFunction(() => [...document.querySelectorAll('video')].some(video => video.currentSrc.includes('demo-source-a.mp4') && video.currentTime >= 11));
        await page.getByText('成片时间轴').waitFor();
        await mkdir(resolve('../../.tmp'), { recursive: true });
        await page.screenshot({ path: resolve('../../.tmp/live-demo-workspace.png') });
      }
      assert.equal(await readFile(filmPath, 'utf8'), beforeFilm);
      assert.equal(await readFile(analysisPath, 'utf8'), beforeAnalysis);
      await page.getByRole('button', { name: '退出演示' }).click();
      await page.getByLabel('商品列表').getByRole('button', { name: '虚构示例甲' }).first().waitFor();
      assert.equal(await readFile(filmPath, 'utf8'), beforeFilm);
      assert.equal(await readFile(analysisPath, 'utf8'), beforeAnalysis);
      assert.equal((await api('/api/projects')).projects.length, projectCountBeforeDemo + 1);
    }
    const panel = page.locator('section').filter({ has: page.getByRole('heading', { name: '候选片段' }) }).last();
    for (const tag of tags) { await page.getByRole('button', { name: new RegExp(`^${tag}\\s+\\d+$`) }).click(); assert.equal(await panel.getByText(`虚构样例${tag}`).count(), 1); for (const other of tags.filter(t => t !== tag)) assert.equal(await panel.getByText(`虚构样例${other}`).count(), 0); }
    await page.getByLabel('商品列表').getByRole('button', { name: '虚构示例丙（未分析）' }).click();
    await page.getByText('当前商品暂无候选片段。').waitFor();
    await page.getByLabel('商品列表').getByRole('button', { name: '虚构示例甲' }).click();
    await page.getByRole('button', { name: /^钩子\s+\d+$/ }).click();
    await panel.getByText('虚构样例钩子').click();
    await page.waitForFunction(() => [...document.querySelectorAll('video')].some(v => v.currentSrc.includes('synthetic-a.mp4') && v.currentTime >= 1));
    const firstSource = await page.locator('video').first().evaluate(v => { v.pause(); return { src: v.currentSrc, time: v.currentTime }; });
    assert.match(firstSource.src, /synthetic-a\.mp4/); assert.ok(firstSource.time >= 1 && firstSource.time < 2.5);
    const productTrack = page.getByLabel('商品区间轨道');
    assert.equal(await productTrack.getByRole('button', { name: '虚构示例甲' }).count(), 2);
    assert.equal(await productTrack.getByRole('button', { name: '虚构示例乙' }).count(), 1);
    const structureTrack = page.getByLabel('结构轨道');
    await structureTrack.getByRole('button', { name: '虚构样例钩子' }).click();
    assert.ok(await page.getByText('虚构样例钩子', { exact: true }).last().isVisible());
    await structureTrack.getByRole('button', { name: '虚构样例痛点' }).click();
    assert.ok(await page.getByText('虚构样例痛点', { exact: true }).last().isVisible());
    await page.getByRole('button', { name: /^行动指令\s+\d+$/ }).click();
    await panel.getByText('虚构样例行动指令').click();
    await page.waitForFunction(() => [...document.querySelectorAll('video')].some(v => v.currentSrc.includes('synthetic-b.mp4') && v.currentTime >= 6));
    const source = await page.locator('video').first().evaluate(v => { v.pause(); return { src: v.currentSrc, time: v.currentTime, duration: v.duration }; });
    assert.match(source.src, /synthetic-b\.mp4/); assert.ok(source.time >= 6 && source.time < 7.5); assert.equal(source.duration, 12);
    assert.ok(await page.getByText('原片时间轴').isVisible());
    const timeline = page.getByText('原片时间轴').locator('..').locator('..');
    assert.ok(await timeline.getByText('0:00', { exact: true }).isVisible());
    assert.ok(await timeline.getByText('00:12:00', { exact: true }).isVisible());
    await page.getByRole('button', { name: '放大时间轴' }).click();
    assert.ok(await timeline.getByText('2×', { exact: true }).isVisible());
    await timeline.getByRole('button', { name: '完整', exact: true }).click();
    assert.ok(await timeline.getByText('1×', { exact: true }).isVisible());
    assert.equal(await readFile(filmPath, 'utf8'), beforeFilm, 'source navigation must not edit film');
    await panel.getByRole('button', { name: '加入成片' }).click();
    await page.waitForTimeout(1800);
    const film = await readFile(join(project.path, 'film.html'), 'utf8');
    assert.match(film, /assets\/synthetic-b\.mp4#t=6,8/);
    const zoom = filmDock.locator('input[type=range]').first(); await zoom.focus(); await zoom.press('Home');
    const block = filmDock.locator('[data-block-kind="video"]').first();
    await block.waitFor();
    const dragEdge = async (edge, dx) => {
      const handle = block.locator(`[data-trim="${edge}"]`);
      const box = await handle.boundingBox();
      assert.ok(box, `missing ${edge} handle`);
      await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
      await page.mouse.down();
      await page.mouse.move(box.x + box.width / 2 + dx, box.y + box.height / 2, { steps: 20 });
      await page.mouse.up();
      await page.waitForTimeout(1400);
      console.log(edge, dx, await block.boundingBox(), (await readFile(filmPath, 'utf8')).match(/assets\/synthetic-b\.mp4#t=[^"< ]+/g));
    };
    const mediaPath = join(project.path, 'assets', 'synthetic-b.mp4');
    const hash = async () => createHash('sha256').update(await readFile(mediaPath)).digest('hex');
    const beforeHash = await hash();
    console.log('initial', await block.boundingBox());
    await dragEdge('start', -30);
    assert.notEqual(await readFile(filmPath, 'utf8'), film, 'magnet at zero must restore earlier source frames');
    await dragEdge('end', 30);
    assert.notEqual(await readFile(filmPath, 'utf8'), film, 'right edge should extend the source range');
    const extendedFilm = await readFile(filmPath, 'utf8');
    await dragEdge('start', 30);
    assert.notEqual(await readFile(filmPath, 'utf8'), extendedFilm, 'left edge should shorten the source range');
    await dragEdge('end', -30);
    const magnet = filmDock.locator('[data-timeline-magnet]');
    console.log('magnet initial', await magnet.getAttribute('data-timeline-magnet'));
    if ((await magnet.getAttribute('data-timeline-magnet')) === '1') await magnet.locator('button').click();
    const b = await block.boundingBox();
    await page.mouse.move(b.x + b.width / 2, b.y + 20); await page.mouse.down(); await page.mouse.move(b.x + b.width / 2 + 100, b.y + 20, { steps: 20 }); await page.mouse.up();
    await page.waitForTimeout(1400);
    console.log('moved', await block.boundingBox(), (await readFile(filmPath, 'utf8')).match(/assets\/synthetic-b\.mp4#t=[^"< ]+/g));
    const movedFilm = await readFile(filmPath, 'utf8');
    await dragEdge('start', -30);
    assert.notEqual(await readFile(filmPath, 'utf8'), movedFilm, 'with space, left edge should restore source frames');
    assert.equal(await hash(), beforeHash);
    await mkdir(resolve('../../.tmp'), { recursive: true });
    await page.screenshot({ path: resolve('../../.tmp/trim-browser.png') });
    const finalFilm = await readFile(filmPath, 'utf8');
    await page.reload();
    await page.waitForTimeout(1500);
    assert.equal(await readFile(filmPath, 'utf8'), finalFilm);
  } finally { await browser?.close(); await studio?.close(); await rm(scratch, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 }); }
});
