import { test } from 'node:test';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { chromium } from 'playwright-core';
import { startStudio } from './server.mjs';
import { filmHtml } from '../../src/film-doc.mjs';

test('source axis with isolated synthetic media', { timeout: 120000 }, async () => {
  const base = resolve(import.meta.dirname, '../../../../.tmp/playback-fix-20261106/source-take'); await mkdir(base, { recursive: true });
  const scratch = await mkdtemp(join(base, 'source-axis-verified-'));
  const oldEnv = Object.fromEntries(['DAOCUT_STUDIO_HOME', 'DAOCUT_LIBRARY', 'DAOCUT_TRASH_DIR', 'DAOCUT_NO_UPDATE_CHECK'].map(k => [k, process.env[k]]));
  process.env.DAOCUT_NO_UPDATE_CHECK = '1';
  process.env.DAOCUT_STUDIO_HOME = join(scratch, 'home'); process.env.DAOCUT_LIBRARY = join(scratch, 'library'); process.env.DAOCUT_TRASH_DIR = join(scratch, 'trash');
  await mkdir(process.env.DAOCUT_TRASH_DIR);
  let studio, browser, step = 'setup';
  try {
    studio = await startStudio({ port: 0, editorDir: process.env.DAOCUT_TEST_EDITOR_DIR ? resolve(process.env.DAOCUT_TEST_EDITOR_DIR) : undefined, openBrowser: () => {} });
    const api = async (path, method = 'GET', body) => {
      const r = await fetch(`${studio.origin}${path}`, { method, headers: { 'x-studio-key': studio.key, ...(body ? { 'content-type': 'application/json' } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
      assert.equal(r.status, 200, 'fixture API failed'); return r.json();
    };
    const { project } = await api('/api/projects', 'POST', { path: join(scratch, 'synthetic-project') });
    await mkdir(join(project.path, 'assets'), { recursive: true });
    for (const name of ['a', 'b']) execFileSync('ffmpeg', ['-v', 'error', '-f', 'lavfi', '-i', 'testsrc2=s=320x180:r=10:d=30', '-f', 'lavfi', '-i', 'sine=frequency=440:duration=30', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-c:a', 'aac', '-shortest', '-y', join(project.path, 'assets', `synthetic-${name}.mp4`)], { windowsHide: true });
    const tags = ['钩子', '痛点', '卖点', '产品演示', '价格锚点', '行动指令'];
    const starts = [1000, 4000, 7000, 10000, 17000, 22000];
    const analysis = { version: 1, sources: ['a', 'b'].map(id => ({ id, assetPath: `assets/synthetic-${id}.mp4`, durationMs: null })), products: [{ id: 'p', name: '合成测试商品', sourceIds: ['a', 'b'] }], intervals: [{ id: 'i', productId: 'p', sourceId: 'a', startMs: 0, endMs: 29000 }, { id: 'j', productId: 'p', sourceId: 'b', startMs: 15000, endMs: 29000 }], candidates: [...tags.map((tag, n) => ({ id: `c${n}`, productId: 'p', intervalId: 'i', sourceId: 'a', startMs: starts[n], endMs: starts[n] + 2500, text: `合成${tag}`, tags: [tag], origin: 'synthetic-test', version: 1 })), { id: 'tiny', productId: 'p', intervalId: 'i', sourceId: 'a', startMs: 3950, endMs: 3999, text: '合成短候选', tags: ['钩子'], origin: 'synthetic-test', version: 1 }, { id: 'multi', productId: 'p', intervalId: 'i', sourceId: 'a', startMs: 12000, endMs: 16000, text: '合成多标签', tags: ['钩子', '痛点'], origin: 'synthetic-test', version: 1 }, { id: 'other', productId: 'p', intervalId: 'j', sourceId: 'b', startMs: 20000, endMs: 23000, text: '合成切换来源', tags: ['行动指令'], origin: 'synthetic-test', version: 1 }] };
    await api(`/api/projects/${project.id}/product-analysis`, 'PUT', { analysis });
    const filmPath = join(project.path, 'film.html');
    await writeFile(filmPath, filmHtml({ stage: { w: 320, h: 180 }, tracks: [{ clips: [{ id: 'synthetic-clip', src: 'assets/synthetic-a.mp4', at: 0, time: [0, 2] }] }] }));
    const before = await readFile(filmPath, 'utf8');
    const analysisPath = join(project.path, '.film', 'product-analysis.json');
    const beforeAnalysis = await readFile(analysisPath, 'utf8');
    const mediaPath = join(project.path, 'assets', 'synthetic-b.mp4');
    const hash = async () => createHash('sha256').update(await readFile(mediaPath)).digest('hex');
    const beforeHash = await hash();
    const hashA = async () => createHash('sha256').update(await readFile(join(project.path, 'assets', 'synthetic-a.mp4'))).digest('hex');
    const beforeHashA = await hashA();
    browser = await chromium.launch({ executablePath: process.env.DAOCUT_TEST_BROWSER || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
    const page = await browser.newPage({ viewport: { width: 1600, height: 1050 } });
    await page.route('**/*', route => [studio.origin, studio.filmOrigin].includes(new URL(route.request().url()).origin) ? route.continue() : route.abort());
    await page.route('**/live-analysis**', route => route.fulfill({ json: { transcription: { status: 'idle', segments: [] }, analysis: { status: 'idle' } } }));
    step = 'open synthetic project';
    await page.goto(`${studio.origin}/projects/${project.id}?key=${studio.key}`);
    await page.getByRole('button', { name: '商品与结构' }).click();
    await page.getByRole('button', { name: '合成测试商品' }).first().waitFor();
    const axis = page.locator('[data-source-axis]'); await axis.waitFor();
    const source = page.locator('[data-timeline-scope="source"]');
    const main = page.locator('[data-timeline-scope="main"]');
    const summary = source.locator('[data-source-selection-summary]');
    const preview = source.locator('[data-source-preview-take]');
    const video = page.locator('video:visible').first();
    const candidate = source.locator('[data-source-candidate="c4"]').first();
    await candidate.waitFor(); await video.waitFor();
    step = 'source track height adjusts and resets';
    assert.equal((await candidate.boundingBox()).height,68);
    const resize=source.locator('[data-track-resize]').first(); const resizeBox=await resize.boundingBox(); assert.ok(resizeBox);
    await page.mouse.move(resizeBox.x+resizeBox.width/2,resizeBox.y+resizeBox.height/2); await page.mouse.down();
    await page.mouse.move(resizeBox.x+resizeBox.width/2,resizeBox.y+resizeBox.height/2+20,{steps:12}); await page.mouse.up();
    assert.ok((await candidate.boundingBox()).height>68,'track head drag increases source block height');
    await source.locator('[data-source-reset-height]').click(); assert.equal((await candidate.boundingBox()).height,68,'standard height button restores default height');
    const sourceRange = async el => ({start:Number(await el.getAttribute('data-source-start')),end:Number(await el.getAttribute('data-source-end'))});
    const atPaused = async (seconds) => page.waitForFunction(s => [...document.querySelectorAll('video')].some(v => v.offsetWidth && v.paused && !v.seeking && Math.abs(v.currentTime-s)<0.22),seconds,{timeout:12000});
    const playTake = async range => {
      await preview.click();
      await page.waitForFunction(({start,end}) => [...document.querySelectorAll('video')].some(v=>v.offsetWidth && !v.paused && v.currentTime>=start/1000-0.15 && v.currentTime<end/1000),range,{timeout:10000});
      await page.locator('[data-preview-range]').waitFor();
      await atPaused(range.end/1000);
      assert.ok(await video.evaluate((v,end)=>v.currentTime>=end/1000-0.2 && v.currentTime<=end/1000+0.12,range.end),'paused at source out point');
    };
    step = 'select candidate without autoplay';
    await page.getByRole('button',{name:/^钩子\s+\d+$/}).click();
    assert.equal(await candidate.locator('[data-preview-muted="true"]').count(),1,'unselected candidate is muted before interaction');
    await candidate.click(); const candidateRange=await sourceRange(candidate);
    assert.equal(await candidate.locator('[data-preview-muted="true"]').count(),1,'selection does not override tag filter');
    await atPaused(candidateRange.start/1000);
    assert.match(await summary.innerText(),/价格锚点/);
    assert.match(await candidate.getAttribute('class'),/z-10/);
    await source.locator('[data-block-kind="video"] img').first().waitFor({timeout:30000});
    await page.waitForFunction(() => [...document.querySelectorAll('[data-timeline-scope="source"] img')].some(i=>i.complete && i.naturalWidth>0),null,{timeout:30000});
    await page.waitForFunction(() => [...document.querySelectorAll('[data-source-candidate="c4"] img')].some(i=>i.complete && i.naturalWidth>0),null,{timeout:30000});
    await page.waitForFunction(() => [...document.querySelectorAll('[data-source-context][data-source-start="24500"] img')].some(i=>i.complete && i.naturalWidth>0),null,{timeout:8000}).catch(() => {});
    await page.waitForFunction(() => { const muted=document.querySelector('[data-source-candidate="c4"] [data-preview-muted="true"]'); return !!muted?.querySelector('img') && !!muted.querySelector('canvas'); },null,{timeout:30000});
    assert.equal(await candidate.locator('[data-preview-muted="true"]').count(),1,'selected nonmatching thumbnail and waveform remain muted');
    await page.evaluate(() => { const label=document.createElement('div'); label.textContent='合成测试·选段预览'; Object.assign(label.style,{position:'fixed',top:'4px',right:'8px',zIndex:'99999',background:'#fff',color:'#111',padding:'3px 8px',fontSize:'12px'}); document.body.appendChild(label); });
    await page.screenshot({path:join(base, 'source-take-preview-verified.png')});
    assert.equal(await readFile(filmPath,'utf8'),before);
    step = 'preview candidate and replay';
    await preview.click();
    await page.waitForFunction(() => [...document.querySelectorAll('video')].some(v=>v.offsetWidth && !v.paused),null,{timeout:10000});
    await candidate.click(); await atPaused(candidateRange.start/1000);
    await playTake(candidateRange);
    const player=video.locator('xpath=../..');
    await player.getByRole('button',{name:'播放',exact:true}).click();
    await page.waitForFunction(({start,end}) => [...document.querySelectorAll('video')].some(v=>v.offsetWidth && !v.paused && v.currentTime>=start/1000-0.15 && v.currentTime<end/1000),candidateRange,{timeout:10000});
    await atPaused(candidateRange.end/1000);
    step = 'shorten candidate without filling exposed footage';
    const contextCount=await source.locator('[data-source-context]').count();
    const sourceDuration=await video.evaluate(v=>v.duration);
    const beforeShortenBox=await candidate.boundingBox(); assert.ok(beforeShortenBox);
    const shortenEdge=await candidate.locator('[data-trim="start"]').boundingBox(); assert.ok(shortenEdge);
    await page.mouse.move(shortenEdge.x+shortenEdge.width/2,shortenEdge.y+shortenEdge.height/2); await page.mouse.down();
    await page.mouse.move(shortenEdge.x+shortenEdge.width/2+20,shortenEdge.y+shortenEdge.height/2,{steps:15}); await page.mouse.up();
    const shortenedCandidate=await sourceRange(candidate);
    assert.ok(shortenedCandidate.start>candidateRange.start && shortenedCandidate.end===candidateRange.end,JSON.stringify(shortenedCandidate));
    const gapMs=(candidateRange.start+shortenedCandidate.start)/2;
    const assertGap=async () => {
      assert.equal(await source.locator('[data-source-context]').count(),contextCount,'shortening does not insert gray source blocks');
      assert.ok(await source.locator('[data-source-start][data-source-end]').evaluateAll((blocks,ms)=>blocks.every(block=>Number(block.dataset.sourceEnd)<=ms || Number(block.dataset.sourceStart)>ms),gapMs),'the exposed portion stays empty on the editable source row');
    };
    await assertGap();
    await page.screenshot({path:join(base, 'no-fill.png')});
    step = 'empty take position still seeks and plays the full original';
    const shortenedBox=await candidate.boundingBox(); assert.ok(shortenedBox);
    const ruler=source.getByRole('slider',{name:'拖动播放头'}); const rulerBox=await ruler.boundingBox(); assert.ok(rulerBox);
    // Move the playhead away first: its 24px grab handle covers this narrow gap.
    await ruler.click({position:{x:20,y:5}});
    await page.waitForFunction(() => [...document.querySelectorAll('video')].some(v=>v.offsetWidth && v.paused && v.currentTime<2));
    await ruler.click({position:{x:(beforeShortenBox.x+shortenedBox.x)/2-rulerBox.x,y:5}});
    await atPaused(gapMs/1000);
    await page.locator('[data-preview-range]').waitFor({state:'detached'});
    assert.equal(await video.evaluate(v=>v.duration),sourceDuration,'the full original duration is independent of take gaps');
    step = 'play original through the empty take position';
    await player.getByRole('button',{name:'播放',exact:true}).click();
    await page.waitForFunction(ms=>[...document.querySelectorAll('video')].some(v=>v.offsetWidth && !v.paused && v.readyState>=2 && v.currentTime>ms/1000),shortenedCandidate.start,{timeout:10000});
    await candidate.click(); await atPaused(shortenedCandidate.start/1000);
    step = 'reload keeps the shortened take and empty position';
    await page.reload(); await page.getByRole('button',{name:'商品与结构'}).click();
    await candidate.waitFor();
    assert.deepEqual(await sourceRange(candidate),shortenedCandidate);
    await assertGap();
    assert.equal(await readFile(filmPath,'utf8'),before); assert.equal(await readFile(analysisPath,'utf8'),beforeAnalysis);
    assert.equal(await hash(),beforeHash); assert.equal(await hashA(),beforeHashA);
    step = 'left card previews adjusted candidate take';
    const candidateEdge=candidate.locator('[data-trim="start"]'); const candidateEdgeBox=await candidateEdge.boundingBox(); assert.ok(candidateEdgeBox);
    await page.mouse.move(candidateEdgeBox.x+candidateEdgeBox.width/2,candidateEdgeBox.y+candidateEdgeBox.height/2); await page.mouse.down();
    await page.mouse.move(candidateEdgeBox.x+candidateEdgeBox.width/2-40,candidateEdgeBox.y+candidateEdgeBox.height/2,{steps:15}); await page.mouse.up();
    const adjustedCandidate=await sourceRange(candidate); assert.ok(adjustedCandidate.start<candidateRange.start,JSON.stringify(adjustedCandidate));
    await page.getByRole('button',{name:/^全部\s+\d+$/}).click();
    const card=page.getByLabel('候选片段').locator('article').filter({hasText:'合成价格锚点'});
    await card.getByRole('button',{name:'预览',exact:true}).click();
    await page.waitForFunction(({start,end}) => [...document.querySelectorAll('video')].some(v=>v.offsetWidth && !v.paused && v.currentTime>=start/1000-0.15 && v.currentTime<start/1000+0.8 && v.currentTime<end/1000),adjustedCandidate,{timeout:10000});
    await atPaused(adjustedCandidate.end/1000);
    step = 'select and preview gray source';
    const initialGray=source.locator('[data-source-context][data-source-start="19500"][data-source-end="22000"]').first();
    const grayId=await initialGray.getAttribute('data-source-context');
    const gray=source.locator(`[data-source-context="${grayId}"]`).first();
    assert.equal(await gray.locator('[data-preview-muted="true"]').count(),1,'unselected gray source is muted');
    await gray.click(); assert.equal(await gray.locator('[data-preview-muted="true"]').count(),1,'ordinary source remains gray when selected'); await atPaused(19.5); assert.match(await summary.innerText(),/原片/);
    await playTake({start:19500,end:22000});
    step = 'trim then preview new gray bounds';
    const endHandle=gray.locator('[data-trim="end"]'); const edge=await endHandle.boundingBox(); assert.ok(edge);
    await page.mouse.move(edge.x+edge.width/2,edge.y+edge.height/2); await page.mouse.down(); await page.mouse.move(edge.x+edge.width/2+20,edge.y+edge.height/2,{steps:15}); await page.mouse.up();
    const trimmed=await sourceRange(gray); assert.ok(trimmed.end>22000,JSON.stringify(trimmed));
    await atPaused(trimmed.start/1000); await playTake(trimmed);
    step = 'source ruler clears range limit';
    await source.getByRole('slider',{name:'拖动播放头'}).click({position:{x:20,y:5}});
    await page.locator('[data-preview-range]').waitFor({state:'detached'});
    step = 'copy and split still work after clearing selection';
    await candidate.click(); await page.keyboard.press('Control+c');
    assert.equal(await readFile(filmPath,'utf8'),before);
    const countBefore=await source.locator('[data-block-id]').count();
    await source.getByRole('button',{name:/^分割/}).first().click();
    const splitBlock=source.locator('[data-source-candidate="c0"]').first(); await splitBlock.click();
    await page.waitForFunction(n=>document.querySelectorAll('[data-timeline-scope="source"] [data-block-id]').length>n,countBefore);
    await source.getByRole('button',{name:/^撤销/}).click();
    await page.waitForFunction(n=>document.querySelectorAll('[data-timeline-scope="source"] [data-block-id]').length===n,countBefore);
    await source.getByRole('button',{name:/^选择/}).first().click();
    step = 'cross-source preview';
    await page.getByLabel('候选显示范围', { exact: true }).getByRole('button', { name: '该商品全部讲解', exact: true }).click();
    await page.getByRole('button',{name:/^行动指令\s+\d+$/}).click();
    await page.getByLabel('候选片段').getByText('合成切换来源').click();
    const other=source.locator('[data-source-candidate="other"]').first(); await other.waitFor();
    await page.waitForFunction(() => [...document.querySelectorAll('video')].some(v=>v.offsetWidth && v.currentSrc.includes('synthetic-b.mp4')));
    const otherRange=await sourceRange(other); await other.click(); await atPaused(otherRange.start/1000); await playTake(otherRange);
    assert.equal(await readFile(filmPath,'utf8'),before); assert.equal(await readFile(analysisPath,'utf8'),beforeAnalysis);
    assert.equal(await hash(),beforeHash); assert.equal(await hashA(),beforeHashA);
  } catch(error) { throw new Error(`Synthetic source preview test failed at: ${step}: ${error.message}`,{cause:error}); }
  finally {
    await browser?.close(); await studio?.close();
    for (const [k,v] of Object.entries(oldEnv)) { if(v===undefined) delete process.env[k]; else process.env[k]=v; }
    await rm(scratch,{recursive:true,force:true,maxRetries:10,retryDelay:200});
  }
});

