import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { createProjectBackup, inspectProjectBackup, restoreProjectBackup } from './project-backup.mjs';
import { associateSharedLibrary, createSharedMediaProject, resolveSharedMedia, sharedMediaManifest } from './shared-media.mjs';
import { mediaContentHash } from '../../src/shared-media-reference.mjs';
import { createSharedAnalysis } from './shared-analysis.mjs';

test('sampled reference and child drafts retain shared identity after a full-content backup and restore', async t => {
  const base = resolve('.tmp/backup-sampled-tests'); await mkdir(base, { recursive: true });
  const dir = await mkdtemp(join(base, 'case-')); t.after(() => rm(dir, { recursive: true, force: true }));
  const keys = ['DAOCUT_STUDIO_HOME', 'DAOCUT_LIBRARY'], old = keys.map(key => process.env[key]);
  t.after(() => keys.forEach((key, i) => old[i] === undefined ? delete process.env[key] : process.env[key] = old[i]));
  process.env.DAOCUT_STUDIO_HOME = join(dir, 'home'); process.env.DAOCUT_LIBRARY = join(dir, 'projects');
  const nas = join(dir, 'nas'); await mkdir(nas); const input = join(nas, 'live.mp4');
  await writeFile(input, Buffer.alloc(10 * 1024 * 1024, 5));
  const library = { id: 'sampled-backup-library', name: 'test', root: nas }; await associateSharedLibrary(library);
  const made = await createSharedMediaProject({ libraryId: library.id, videoPath: 'live.mp4', requestId: 'sampled-backup-01' });
  const analysis = JSON.parse(await readFile(join(made.project.path, '.film/product-analysis.json'))), source = analysis.sources[0]; source.durationMs = 10000;
  await writeFile(join(made.project.path, '.film/product-analysis.json'), JSON.stringify(analysis));
  const draftId = 'b'.repeat(24), draft = join(made.project.path, '.film/structure-drafts', draftId);
  await mkdir(join(draft, '.film'), { recursive: true }); await mkdir(join(draft, 'assets'));
  await writeFile(join(draft, '.film/id'), 'sampled-child');
  await writeFile(join(draft, 'film.html'), '<html>personal edit</html>');
  await writeFile(join(draft, '.film/structure-draft.json'), JSON.stringify({ version: 1, draftId, parentRelative: '../../..', parentProjectId: made.project.id }));
  await writeFile(join(draft, 'assets/.daocut-source-media.json'), JSON.stringify(await sharedMediaManifest(made.project.path)));
  const shared = createSharedAnalysis({ settings: () => ({ enabled: true, resultRoots: [{ libraryId: library.id, root: nas }] }), coordinate: async () => ({ task: null, coordinationId: 'a'.repeat(64) }) });
  const before = await shared.prepare(made.project.path, source, { action: 'transcription' });
  const backup = join(dir, 'backup'), restored = join(dir, 'restored');
  await createProjectBackup(made.project.path, backup); const info = await inspectProjectBackup(backup);
  assert.equal(info.sources[0].sha256, await mediaContentHash(input));
  assert.equal(info.sources[0].identitySha256, made.source.sha256); assert.notEqual(info.sources[0].sha256, made.source.sha256);
  await restoreProjectBackup({ backupPath: backup, targetPath: restored, expectedBackupId: info.backupId, confirmed: true, mappings: [{ libraryId: library.id, root: nas }] });
  const record = (await sharedMediaManifest(restored)).items[made.asset];
  assert.equal(record.sha256, made.source.sha256); assert.equal(record.identityKind, made.source.identityKind);
  assert.equal((await resolveSharedMedia(restored, made.asset)).path, (await resolveSharedMedia(made.project.path, made.asset)).path);
  const after = await shared.prepare(restored, source, { action: 'transcription' });
  assert.equal(after.sourceIdentity, before.sourceIdentity); assert.equal(after.taskKey, before.taskKey);
  const child = (await sharedMediaManifest(join(restored, '.film/structure-drafts', draftId))).items[made.asset];
  assert.equal(child.sha256, record.sha256); assert.equal(child.identityKind, record.identityKind);
});
